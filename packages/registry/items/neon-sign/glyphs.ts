/**
 * 灯管字形表。坐标以字高为 1：y 从 0（顶）到 1（基线），x 从 0 到字宽 w。
 * 指令与上游相同：M/L 直线，Q 二次曲线，R = arcTo（拐角处弯管），E = ellipse（cx, cy, rx, ry, 起角, 止角, 逆时针）。
 * 每个 sub 是一根独立的灯管，非闭合的两端会画上黑色封头；G L A S B O W N 照抄上游，其余字形按同样的弯管写法补齐。
 */
export type GlyphCommand =
  | readonly ['M', number, number]
  | readonly ['L', number, number]
  | readonly ['Q', number, number, number, number]
  | readonly ['R', number, number, number, number, number]
  | readonly ['E', number, number, number, number, number, number, number]

export interface GlyphTube {
  closed?: 1
  c: readonly GlyphCommand[]
}

export interface Glyph {
  w: number
  sub: readonly GlyphTube[]
}

const P = Math.PI

/** 小圆点：闭合的一小圈灯管，描边后就是一颗实心点。 */
function dot(x: number, y: number): GlyphTube {
  return { closed: 1, c: [['M', x + 0.04, y], ['E', x, y, 0.04, 0.04, 0, 2 * P, 0]] }
}

