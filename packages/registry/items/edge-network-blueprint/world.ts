/* ---------- 投影：等距圆柱，北纬 80° 到南纬 58° ---------- */

export const MAP_TOP = 80
export const MAP_BOTTOM = -58
export const MAP_W = 720
export const MAP_H = (MAP_TOP - MAP_BOTTOM) * 2
export const MAP_ASPECT = MAP_W / MAP_H

export function project([lon, lat]: LonLat): [number, number] {
  return [(lon + 180) * 2, (MAP_TOP - lat) * 2]
}

export function polygonPath(rings: readonly (readonly LonLat[])[]): string {
  return rings
    .map((ring) =>
      ring
        .map((point, i) => {
          const [x, y] = project(point)
          return `${i === 0 ? 'M' : 'L'}${x.toFixed(1)} ${y.toFixed(1)}`
        })
        .join('')
        .concat('Z'),
    )
    .join('')
}

